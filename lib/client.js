    const COLORS = {
      good: 'var(--dsw-alias-state-success-primary, #2e7d32)',
      warn: 'var(--dsw-alias-state-warn-primary, #b26a00)',
      bad: 'var(--dsw-alias-state-error-primary, #c62828)',
    };

    function toneOf(score) {
      if (score === null || score === undefined) return 'warn';
      if (score >= 4) return 'good';
      if (score >= 3) return 'warn';
      return 'bad';
    }

    function toneColor(score) {
      return COLORS[toneOf(score)];
    }

    function fmt(value) {
      return value === null || value === undefined ? '—' : String(Math.round(value * 10) / 10);
    }

    function fillPercent(score) {
      const value = score === null || score === undefined ? 0 : score;
      return Math.min(100, Math.max(0, value / 5 * 100));
    }

    function verdictKey(score) {
      if (score === null || score === undefined) return 'panel.verdict.fair';
      if (score >= 4) return 'panel.verdict.good';
      if (score >= 3) return 'panel.verdict.fair';
      return 'panel.verdict.bad';
    }

    function kindLabel(kind) {
      if (kind === 'anti_pattern') return 'panel.kind.anti';
      if (kind === 'dont') return 'panel.kind.dont';
      if (kind === 'requirement') return 'panel.kind.requirement';
      return 'panel.kind.script';
    }

