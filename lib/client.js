    // The panel is global while results are per call, so the latest results live
    // in one small store that both the card and the panel subscribe to.
    let history = [];
    const listeners = new Set();

    function addReport(meta, callId) {
      if (meta === null || meta === undefined) return;
      // callId is stable across remounts, so a re-render cannot duplicate the
      // same check in the history list.
      if (callId !== undefined && history.some((row) => row.id === callId)) return;
      const entry = {
        id: callId ?? `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
        at: Date.now(),
        meta,
      };
      history = [entry, ...history].slice(0, 12);
      for (const listener of listeners) listener();
    }

    function subscribe(listener) {
      listeners.add(listener);
      return () => listeners.delete(listener);
    }

    function snapshot() {
      return history;
    }

